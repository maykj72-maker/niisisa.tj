const journalPhoto = (page: number, image: number) =>
  `/company/page-${String(page).padStart(2, "0")}-image-${String(image).padStart(2, "0")}.webp`;

const photo = (
  page: number,
  image: number,
  caption: string,
  alt = caption,
  document = false,
  orientation?: "portrait" | "wide",
): OrganizationPhoto => ({
  src: journalPhoto(page, image),
  alt,
  caption,
  document,
  orientation,
});

